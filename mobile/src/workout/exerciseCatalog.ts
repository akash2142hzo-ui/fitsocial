export type ExerciseName = (typeof rows)[number][1] | (typeof cardioRows)[number][1];
export type ExerciseId = (typeof rows)[number][0] | (typeof cardioRows)[number][0];
export const exerciseCatalog: readonly (ExerciseDefinition & { readonly name: ExerciseName })[] =
  [...rows.map(([id, name, muscle, equipment]) => ({ id, name, muscle, equipment,
    supportedMetrics: [] as readonly CardioMetric[], allowZeroWeight: ["Machine", "Cable", "Smith machine", "Resistance band"].includes(equipment),
    tracking: /^(Plank|Side Plank|Hollow Body Hold|Dead Hang|Reverse Plank|Bear Plank|RKC Plank|Forearm Side Plank|Copenhagen Plank|L-Sit Hold|Hanging Scapular Hold|Superman Hold|Wall Sit)$/.test(name) ? "duration"
      : /Assisted/.test(name) ? "assisted" : equipment === "Bodyweight" ? "bodyweight" : "external" as TrackingType,
    aliases: [name.replace(/Dumbbell/g, "DB").replace(/Barbell/g, "BB").replace(/Romanian Deadlift/g, "RDL"),
      name.replace(/Pull-up/g, "pullup").replace(/Push-up/g, "pushup").replace(/Chin-up/g, "chinup")],
  })), ...cardioRows.map(([id, name, cardioCategory, equipment, supportedMetrics]) => ({ id, name, cardioCategory, equipment, supportedMetrics,
    muscle: "Cardio" as const, tracking: "cardio" as const, allowZeroWeight: false,
    aliases: [name.replace(/Walking/g, "walk").replace(/Running/g, "run"), ...(name === "Air Bike" ? ["Assault Bike"] : []), ...(name === "Swimming" ? ["swim"] : [])],
  }))];
export const exercises: readonly ExerciseName[] = exerciseCatalog.map((exercise) => exercise.name);
export type ExerciseFilters = { query?: string; muscle?: MuscleGroup | "All"; equipment?: Equipment | "All" };
export function searchExercises({ query = "", muscle = "All", equipment = "All" }: ExerciseFilters = {}) {
  const tokens = query.toLowerCase().trim().split(/[\s-]+/).filter(Boolean);
  return exerciseCatalog.filter((exercise) =>
    (muscle === "All" || exercise.muscle === muscle)
    && (equipment === "All" || exercise.equipment === equipment)
    && tokens.every((token) => [exercise.name, ...exercise.aliases].join(" ").toLowerCase().includes(token)));
}
